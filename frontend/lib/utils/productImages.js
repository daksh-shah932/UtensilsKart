/**
 * Returns an accurate image array for any product.
 * If the product only has a legacy generic image, it resolves to the accurate utensil image.
 */
export function getProductImages(product) {
  if (!product) {
    return [ITEM_NAME_IMAGES["Kadai"][0]];
  }

  const name = product.name || product.item_name || "";
  const cat = (product.category || "").toLowerCase();

  // If product already has custom images AND it's not the generic duplicate
  const existing = Array.isArray(product.images) && product.images.length > 0
    ? product.images
    : (product.image || product.imageUrl || product.img ? [product.image || product.imageUrl || product.img] : []);

  const hasSpecificImage = existing.length > 0 && !existing.every(u => {
    if (!u) return true;
    const base = u.split("?")[0];
    return base.includes("photo-1556909114-f6e7ad7d3136") || (name !== "Kadai" && base.includes("photo-1592156328757-ae2941276b2c"));
  });

  if (hasSpecificImage) {
    return existing;
  }

  // Direct match on item_name
  if (ITEM_NAME_IMAGES[name]) {
    return ITEM_NAME_IMAGES[name];
  }

  // Fuzzy match on item name
  const lower = name.toLowerCase();
  for (const [key, imgs] of Object.entries(ITEM_NAME_IMAGES)) {
    if (lower.includes(key.toLowerCase()) || key.toLowerCase().includes(lower)) {
      return imgs;
    }
  }

  // Keywords
  if (lower.includes("kadai") || lower.includes("karahi")) return ITEM_NAME_IMAGES["Kadai"];
  if (lower.includes("tawa")) return ITEM_NAME_IMAGES["Tawa"];
  if (lower.includes("pressure cooker") || lower.includes("cooker")) return ITEM_NAME_IMAGES["Pressure Cooker"];
  if (lower.includes("knife") || lower.includes("cleaver")) return ITEM_NAME_IMAGES["Chef Knife"];
  if (lower.includes("spoon") || lower.includes("ladle")) return ITEM_NAME_IMAGES["Spoon (Table)"];
  if (lower.includes("fork")) return ITEM_NAME_IMAGES["Fork"];
  if (lower.includes("bottle") || lower.includes("flask")) return ITEM_NAME_IMAGES["Water Bottle"];
  if (lower.includes("tiffin") || lower.includes("lunch box") || lower.includes("dabba")) return ITEM_NAME_IMAGES["Lunch Box"];
  if (lower.includes("container") || lower.includes("canister") || lower.includes("jar")) return ITEM_NAME_IMAGES["Canister"];
  if (lower.includes("masala") || lower.includes("spice")) return ITEM_NAME_IMAGES["Spice Box (Masala Dabba)"];
  if (lower.includes("plate") || lower.includes("thali")) return ITEM_NAME_IMAGES["Dinner Plate"];
  if (lower.includes("bowl") || lower.includes("katori")) return ITEM_NAME_IMAGES["Bowl (Katori)"];
  if (lower.includes("glass") || lower.includes("tumbler")) return ITEM_NAME_IMAGES["Glass (Tumbler)"];
  if (lower.includes("tray") || lower.includes("sheet")) return ITEM_NAME_IMAGES["Baking Tray"];
  if (lower.includes("mould") || lower.includes("tin")) return ITEM_NAME_IMAGES["Cake Mould"];
  if (lower.includes("whisk")) return ITEM_NAME_IMAGES["Whisk"];
  if (lower.includes("grater") || lower.includes("slicer")) return ITEM_NAME_IMAGES["Grater"];
  if (lower.includes("tongs") || lower.includes("chimta")) return ITEM_NAME_IMAGES["Tongs"];
  if (lower.includes("colander") || lower.includes("strainer")) return ITEM_NAME_IMAGES["Colander"];
  if (lower.includes("pan") || lower.includes("skillet")) return ITEM_NAME_IMAGES["Frying Pan"];
  if (lower.includes("pot") || lower.includes("patila") || lower.includes("tope")) return ITEM_NAME_IMAGES["Stock Pot"];

  // Category fallback
  for (const [cKey, imgs] of Object.entries(CATEGORY_FALLBACK_IMAGES)) {
    if (cat.includes(cKey)) return imgs;
  }

  return ITEM_NAME_IMAGES["Kadai"];
}

/**
 * Returns single primary image URL for a product card.
 */
export function getProductPrimaryImage(product) {
  const imgs = getProductImages(product);
  return imgs[0] || "https://images.unsplash.com/photo-1592156328757-ae2941276b2c?w=800&q=80";
}
